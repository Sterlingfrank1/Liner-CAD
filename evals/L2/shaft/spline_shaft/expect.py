def expect(e):
    e.dim(value=120)
    e.dim(e.feature(cyl=30, where="right"), fit="k6")
    e.dim(e.feature(cyl=30, where="right"), fit="k6")
    e.datum("A", on=e.feature(cyl=30), axis=True)
    e.datum("B", on=e.feature(cyl=30), axis=True)
    e.gtol("circular_runout", on=e.face("left"), datums=["A", "B"], max=0.03)
    e.rough(e.face("top"), ra_max=0.8)
    e.note(contains="调质处理 28~")
    e.view("front", must=False)
    e.view("left", must=False)
